"""Deterministic nutrition math.

Every number shown to the user comes from data/foods.csv, never from the
language model. foods.csv is generated by scripts/build_foods.py from two
published tables, and each row keeps its source record ID:
  - IFCT 2017: Indian Food Composition Tables, National Institute of Nutrition
  - USDA SR28: USDA National Nutrient Database for Standard Reference, Release 28
Values are per 100 g edible portion; carbs are total carbohydrate (fibre included).
"""

from __future__ import annotations

import csv
import re
import unicodedata
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from types import MappingProxyType

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
NUTRIENTS = ("kcal", "carbs_g", "fiber_g", "protein_g", "fat_g", "sat_fat_g", "sodium_mg")


@dataclass(frozen=True)
class Food:
    name: str
    aliases: tuple[str, ...]
    category: str
    default_g: float
    per100: MappingProxyType  # read-only nutrient -> value per 100 g
    source: str
    source_id: str
    source_desc: str


# Quantity, unit and preparation words that can surround an ingredient name.
FILLER = set(
    ["a", "an", "the", "of", "some", "few", "little", "bit", "half", "whole", "fresh", "chopped", "sliced", "diced", "minced", "grated", "boiled", "raw", "dry", "dried", "cooked", "big", "small", "medium", "large", "cup", "cups", "katori", "katoris", "bowl", "bowls", "tbsp", "tsp", "tablespoon", "tablespoons", "teaspoon", "teaspoons", "spoon", "spoons", "g", "gm", "gms", "gram", "grams", "kg", "ml", "l", "litre", "liter", "handful", "handfuls", "pinch", "bunch", "bunches", "piece", "pieces", "clove", "cloves", "can", "cans", "packet", "pack", "slice", "slices", "sheet", "sheets", "stick", "sticks", "to", "taste", "as", "needed"]
)
# Colour/variety words that don't change the food much ("red onion" is still onion).
SAFE_ADJECTIVES = {"red", "white", "yellow", "purple", "baby", "ripe", "organic", "frozen", "plain", "unsalted", "salted", "lean", "skinless", "boneless"}


def normalize(text: str) -> str:
    """Lowercase, fold accents (azúcar -> azucar), strip punctuation, collapse spaces."""
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"\s+", " ", re.sub(r"[^a-z ]", " ", text.lower())).strip()


@lru_cache
def foods() -> dict[str, Food]:
    table: dict[str, Food] = {}
    with open(DATA_DIR / "foods.csv", newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            table[row["name"]] = Food(
                name=row["name"],
                aliases=tuple(a.strip() for a in row["aliases"].split("|") if a.strip()),
                category=row["category"],
                default_g=float(row["default_g"]),
                per100=MappingProxyType({k: float(row[k]) for k in NUTRIENTS}),
                source=row["source"],
                source_id=row["source_id"],
                source_desc=row["source_desc"],
            )
    return table


@lru_cache
def _alias_index() -> dict[str, str]:
    """Normalized alias (or canonical name) -> canonical name."""
    index: dict[str, str] = {}
    for food in foods().values():
        for alias in (food.name, *food.aliases):
            index.setdefault(normalize(alias), food.name)
    return index


@lru_cache
def _alias_patterns() -> tuple[tuple[str, re.Pattern], ...]:
    """Compiled word-boundary patterns, longest alias first."""
    return tuple(
        (alias, re.compile(rf"\b{re.escape(alias)}\b"))
        for alias in sorted(_alias_index(), key=len, reverse=True)
    )


def canonical_names() -> list[str]:
    return sorted(foods())


@lru_cache(maxsize=2048)
def match(item: str) -> Food | None:
    """Map an ingredient name to a food in the table, or None.

    Strict on purpose: after dropping quantities and units, the remaining words
    must be a known name (optionally with a colour/variety word in front).
    "peanut butter" or "rice flour" stay unmatched instead of being counted as
    butter or flour; unmatched items are shown to the user as "not counted".
    """
    index = _alias_index()
    words = normalize(item).split()
    # Peel filler words off the front one at a time, checking at each step, so
    # "1 cup gram flour" stops at "gram flour" even though "gram" is also a unit.
    while words:
        trimmed = list(words)
        while len(trimmed) > 1 and trimmed[-1] in FILLER:  # "onions chopped", "salt to taste"
            trimmed.pop()
        for candidate in (words, trimmed):
            core = " ".join(candidate)
            if core in index:
                return foods()[index[core]]
            if len(candidate) >= 2 and candidate[0] in SAFE_ADJECTIVES and " ".join(candidate[1:]) in index:
                return foods()[index[" ".join(candidate[1:])]]
        if words[0] not in FILLER:
            return None
        words.pop(0)
    return None


def find_mentions(text: str) -> list[tuple[Food, int]]:
    """Foods mentioned in free text with their first offset.

    Takes every match, keeps the longest non-overlapping spans, so
    "brown rice, then plain rice" yields both brown rice and white rice.
    """
    norm = normalize(text)
    index = _alias_index()
    taken: list[tuple[int, int]] = []
    first_pos: dict[str, int] = {}
    for alias, pattern in _alias_patterns():
        for m in pattern.finditer(norm):
            start, end = m.span()
            if any(start < e and s < end for s, e in taken):
                continue
            taken.append((start, end))
            name = index[alias]
            first_pos[name] = min(first_pos.get(name, start), start)
    return [(foods()[name], pos) for name, pos in sorted(first_pos.items(), key=lambda kv: kv[1])]


def totals(ingredients: list[dict]) -> dict:
    """Sum nutrients for [{"item", "grams"}]; unknown items are listed, not guessed."""
    out: dict = {k: 0.0 for k in NUTRIENTS}
    uncounted: list[str] = []
    for ing in ingredients:
        food = match(ing["item"])
        grams = float(ing.get("grams") or 0)
        if food is None:
            uncounted.append(ing["item"])
            continue
        for k in NUTRIENTS:
            out[k] += food.per100[k] * grams / 100
    out["uncounted"] = uncounted
    return out


def per_serving(ingredients: list[dict], servings: int) -> dict:
    servings = max(int(servings or 1), 1)
    total = totals(ingredients)
    result = {k: round(total[k] / servings, 1) for k in NUTRIENTS}
    result["net_carbs_g"] = round(max(result["carbs_g"] - result["fiber_g"], 0), 1)
    result["uncounted"] = total["uncounted"]
    return result


def sources_for(ingredients: list[dict]) -> list[dict]:
    """The published record behind each counted ingredient."""
    seen: dict[str, dict] = {}
    for ing in ingredients:
        food = match(ing["item"])
        if food and food.name not in seen:
            seen[food.name] = {"item": food.name, "source": food.source, "id": food.source_id, "record": food.source_desc}
    return list(seen.values())
